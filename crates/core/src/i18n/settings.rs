// pages, in the cards' order.

/// One option of a choice row: its label (as on the button) and what it does.
/// The help card's `Choice` type is this, re-exported by the UI.
#[derive(Clone, Copy, Debug)]
pub struct ChoiceText {
    pub label: &'static str,
    pub help: &'static str,
}

/// A [`ChoiceText`] (the statics below say how the pair is made).
const fn ch(label: &'static str, help: &'static str) -> ChoiceText {
    ChoiceText { label, help }
}

