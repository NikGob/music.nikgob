locale_table! {
    /// Returns the settings cards' short words for `loc`.
    settings_misc_in -> SettingsMisc,
    /// Returns the settings cards' short words for the active process locale.
    settings_misc,
    { Ru => MISC_RU, En => MISC_EN }
}

/// Formats `n` gigabytes (`"50 ГБ"` / `"50 GB"`).
pub fn fmt_gb_in(loc: Locale, n: u32) -> String {
    format!("{n} {}", super::common_in(loc).gb)
}

/// Formats `n` days (`"30 дн."` / `"30 d"`).
pub fn fmt_days_in(loc: Locale, n: u32) -> String {
    format!("{n} {}", settings_misc_in(loc).days_short)
}

/// Formats `x` with one digit after the point and the locale's decimal
/// mark (`"3,5"` / `"3.5"`).
pub fn fmt_one_decimal_in(loc: Locale, x: f32) -> String {
    let s = format!("{x:.1}");
    match loc {
        Locale::Ru => s.replace('.', ","),
        Locale::En => s,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gb_and_days_follow_the_locale() {
        assert_eq!(fmt_gb_in(Locale::Ru, 50), "50 ГБ");
        assert_eq!(fmt_gb_in(Locale::En, 50), "50 GB");
        assert_eq!(fmt_days_in(Locale::Ru, 30), "30 дн.");
        assert_eq!(fmt_days_in(Locale::En, 30), "30 d");
    }

    #[test]
    fn one_decimal_uses_the_locales_mark() {
        assert_eq!(fmt_one_decimal_in(Locale::Ru, 3.5), "3,5");
        assert_eq!(fmt_one_decimal_in(Locale::En, 3.5), "3.5");
    }
}
